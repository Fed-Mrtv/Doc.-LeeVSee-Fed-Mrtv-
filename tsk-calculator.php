<?php
/**
 * Выполняет базовую арифметическую операцию над двумя числами.
 *
 * @param float|int $a Первое число
 * @param float|int $b Второе число
 * @param string $operation Символ операции: +, -, *, /, **
 * @return float|int|string Результат вычисления или строка с ошибкой
 */
function calculator($a, $b, string $operation)
{
    // 1. Проверка корректности аргументов: являются ли они числами
    if (!is_numeric($a) || !is_numeric($b)) {
        return 'Ошибка: оба аргумента должны быть числами.';
    }

    // Приведение к числу для корректной работы арифметики
    $a = $a + 0;
    $b = $b + 0;

    // 2. Проверка поддерживаемых операций
    $allowedOperations = ['+', '-', '*', '/', '**'];
    if (!in_array($operation, $allowedOperations, true)) {
        return 'Ошибка: неизвестная операция. Поддерживаются: +, -, *, /, **';
    }

    // 3. Проверка деления на ноль
    if ($operation === '/' && $b == 0) {
        return 'Ошибка: деление на ноль недопустимо.';
    }

    // 4. Выполнение вычисления
    switch ($operation) {
        case '+':
            return $a + $b;
        case '-':
            return $a - $b;
        case '*':
            return $a * $b;
        case '/':
            return $a / $b;
        case '**':
            // Оператор возведения в степень ** доступен в PHP 5.6+
            return $a ** $b;
    }

    // Техническая заглушка, которая никогда не будет достигнута
    // из-за проверки in_array выше, но нужна для удовлетворения анализаторов кода.
    return 'Неизвестная ошибка.';
}

/* --- Примеры использования --- */

// Тест 1: Корректное сложение
$result1 = calculator(15, 5, '+');
echo "15 + 5 = " . $result1 . PHP_EOL; // Выведет: 15 + 5 = 20

// Тест 2: Возведение в степень
$result2 = calculator(2, 10, '**');
echo "2 ** 10 = " . $result2 . PHP_EOL; // Выведет: 2 ** 10 = 1024

// Тест 3: Деление на ноль
$result3 = calculator(10, 0, '/');
echo "10 / 0 = " . $result3 . PHP_EOL; // Выведет: 10 / 0 = Ошибка: деление на ноль недопустимо.

// Тест 4: Неизвестная операция
$result4 = calculator(10, 5, '%');
echo "10 % 5 = " . $result4 . PHP_EOL; // Выведет: 10 % 5 = Ошибка: неизвестная операция...

// Тест 5: Некорректный ввод (строка вместо числа)
$result5 = calculator("abc", 5, '+');
echo "abc + 5 = " . $result5 . PHP_EOL; // Выведет: abc + 5 = Ошибка: оба аргумента должны быть числами.

// Тест 6: Работа с отрицательными числами и вычитанием
$result6 = calculator(-5, 3, '-');
echo "-5 - 3 = " . $result6 . PHP_EOL; // Выведет: -5 - 3 = -8